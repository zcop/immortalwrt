def compose(controller: Path, destroy_override: Path | None) -> str:
    src = controller.read_text()
    match = MAX_NODES_RE.search(src)
    if not match:
        raise HarnessError("DSA_NSS_MAX_NODES not found in controller source")

    functions = [
        extract_function(src, "dsa_nss_is_root"),
        extract_function(src, "dsa_nss_node_owned_by"),
        extract_function(src, "dsa_nss_node_destroy"),
    ]
    destroy = extract_function(src, "dsa_nss_destroy_nodes")
    if destroy_override is not None:
        destroy = destroy_override.read_text()
        if "dsa_nss_destroy_nodes" not in destroy:
            raise HarnessError(
                f"{destroy_override}: no dsa_nss_destroy_nodes() replacement"
            )
    functions.append(destroy)

    return (
        PREAMBLE.replace("@MAX_NODES@", match.group(1))
        + extract_struct(src, "dsa_nss_node")
        + ";\n"
        + TABLE
        + "\n"
        + "\n\n".join(functions)
        + "\n"
        + SCAFFOLDING
    )


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--controller",
        type=Path,
        default=root / "package/kernel/qca-nss-qinq/src/qca_nss_qinq.c",
        help="qca_nss_qinq.c to extract the functions from",
    )
    parser.add_argument(
        "--destroy-nodes",
        type=Path,
        help="file whose text replaces dsa_nss_destroy_nodes() (negative control)",
    )
    parser.add_argument("--cc", default="cc", help="C compiler to use")
    args = parser.parse_args()

    try:
        program = compose(args.controller, args.destroy_nodes)
    except (HarnessError, OSError) as err:
        print(f"harness: {err}", file=sys.stderr)
        return 2

    with tempfile.TemporaryDirectory(prefix="qinq-lifetime-") as tmp:
        source = Path(tmp) / "test.c"
        binary = Path(tmp) / "test"
        source.write_text(program)
        build = subprocess.run(
            [args.cc, "-std=gnu11", "-Wall", "-Wextra", "-Werror",
             "-Wno-unused-parameter", "-Wno-unused-function", "-O0",
             "-o", str(binary), str(source)],
            capture_output=True,
            text=True,
        )
        if build.returncode:
            print(build.stdout, end="", file=sys.stderr)
            print(build.stderr, end="", file=sys.stderr)
            return 2
        run = subprocess.run([str(binary)], capture_output=True, text=True)
        print(run.stdout, end="")
        print(run.stderr, end="", file=sys.stderr)
        return run.returncode


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Exercise the production single-rate queue TBF register profile.

yt921x_qsch_tbf_apply_raw() and yt921x_qsch_flow_index() are extracted from
yt921x_qos_tc.c; the shaper/index constants come from yt921x_enhanced.h.
Named fake register and conversion helpers keep the test arguments visible
while checking WORD0/CIR-CBS, WORD1=0, and the gated WORD2 profile.

Usage:
    tools/nss/test_yt921x_queue_rate.py
    tools/nss/test_yt921x_queue_rate.py --sanitize address,undefined,leak
    tools/nss/test_yt921x_queue_rate.py --negative

--negative replaces only the extracted WORD1 zero write with the old
CIR/CBS budget; it must compile and fail the semantic checks.
"""


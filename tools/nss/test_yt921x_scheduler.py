    brace = source.find("{", match.start(), match.end())
    end = _match_delim(source, brace, "{", "}")
    if source[end + 1:end + 2] != ";":
        raise HarnessError(f"struct {name} has no terminating semicolon")
    return source[match.start():end + 2]



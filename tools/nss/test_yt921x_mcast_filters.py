#!/usr/bin/env python3
"""Exercise the real yt921x_apply_flood_filters_locked() C body.

The function is extracted from yt921x_core.c and compiled against fake
register and DSA accessors.  Expected values are derived from the preserved
port bases, not by mirroring the implementation.  No hardware is touched.

Usage:
    tools/nss/test_yt921x_mcast_filters.py
    tools/nss/test_yt921x_mcast_filters.py --sanitize
    tools/nss/test_yt921x_mcast_filters.py --source old/yt921x_core.c
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))

from test_qinq_node_lifetime import HarnessError, extract_function  # noqa: E402

APPLY_DEF_RE = re.compile(
    r"(?m)^int[ \t]+yt921x_apply_flood_filters_locked[ \t]*"
    r"\([^;{}]*\)\s*\{"
)


def extract_apply(src: str) -> str:
    match = APPLY_DEF_RE.search(src)
    if not match:
        raise HarnessError(
            "global int yt921x_apply_flood_filters_locked() definition not found"
        )
    return extract_function(
        src[match.start():], "yt921x_apply_flood_filters_locked"
    )

PREAMBLE = r"""/* generated by test_yt921x_mcast_filters.py; do not edit */
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef unsigned int u32;

#define BIT(n) (1u << (n))
#define EIO 5
#define YT921X_FILTER_PORTS_M 0x7ffu
#define YT921X_MCAST_STATIC_ROUTER_PORT 0x100u
#define YT921X_MCAST_STATIC_ROUTER_PORT_M 0x7ffu
#define YT921X_FILTER_UNK_UCAST 0x104u
#define YT921X_FILTER_UNK_MCAST 0x108u
#define YT921X_FILTER_MCAST 0x10cu
#define YT921X_FILTER_BCAST 0x110u

struct dsa_switch {
	u32 user_mask;
};

struct yt921x_priv {
	u32 flood_unk_ucast_base_mask;
	u32 flood_mcast_base_mask;
	u32 flood_bcast_base_mask;
	u32 flood_storm_mask;
	struct dsa_switch ds;
};

static u32 yt921x_user_ports_mask(struct dsa_switch *ds)
{
	return ds->user_mask;
}

static int read_count, write_count, failures;
static int fail_read, fail_write = -1;
static u32 router_value;
static u32 write_reg[4], write_val[4];

static void failf(const char *fmt, ...)
{
	va_list ap;

	failures++;
	if (failures > 20)
		return;
	va_start(ap, fmt);
	vprintf(fmt, ap);
	va_end(ap);
	putchar('\n');
}

static int yt921x_reg_read(struct yt921x_priv *priv, u32 reg, u32 *val)
{
	(void)priv;
	read_count++;
	if (fail_read)
		return -EIO;
	if (reg != YT921X_MCAST_STATIC_ROUTER_PORT || write_count)
		failf("read: reg=0x%x writes_before=%d", reg, write_count);
	*val = router_value;
	return 0;
}

static int yt921x_reg_write(struct yt921x_priv *priv, u32 reg, u32 val)
{
	(void)priv;
	if (fail_write == write_count) {
		write_count++;
		return -EIO;
	}
	if (write_count >= 4) {
		failf("write: more than four writes");
		return -EIO;
	}
	write_reg[write_count] = reg;
	write_val[write_count] = val;
	write_count++;
	return 0;
}
"""

SCAFFOLDING = r"""
static const u32 contexts[2] = {
	BIT(10),			/* native */
	BIT(10) | BIT(4) | BIT(8),	/* standard, CPU conduit */
};
static const int user_bits[] = { 0, 1, 2, 3 };
static const int storm_bits[] = { 0, 1, 2, 3, 10 };
static const int router_bits[] = { 0, 1, 2, 3, 4, 8, 10 };

static u32 bits_to_mask(const int *bits, int count, int subset)
{
	u32 mask = 0;
	int i;

	for (i = 0; i < count; i++)
		if (subset & BIT(i))
			mask |= BIT(bits[i]);
	return mask;
}

static void reset_ops(void)
{
	read_count = write_count = 0;
	fail_read = 0;
	fail_write = -1;
	router_value = 0;
	memset(write_reg, 0, sizeof(write_reg));
	memset(write_val, 0, sizeof(write_val));
}

static void check_ok(const char *label, int ret, const u32 expect[4])
{
	static const u32 regs[4] = {
		YT921X_FILTER_UNK_UCAST, YT921X_FILTER_UNK_MCAST,
		YT921X_FILTER_MCAST, YT921X_FILTER_BCAST,
	};
	int i;

	if (ret)
		failf("%s: ret=%d", label, ret);
	if (read_count != 1)
		failf("%s: read_count=%d", label, read_count);
	if (write_count != 4) {
		failf("%s: write_count=%d", label, write_count);
		return;
	}
	for (i = 0; i < 4; i++)
		if (write_reg[i] != regs[i] || write_val[i] != expect[i])
			failf("%s: write %d reg=0x%x val=0x%x want reg=0x%x val=0x%x",
			      label, i, write_reg[i], write_val[i], regs[i], expect[i]);
}

/* Exhaustive over user flags {0..3}, storm {0,1,2,3,10} and router
 * {0,1,2,3,4,8,10}, for both preserved base contexts.
 */
static void test_matrix(void)
{
	u32 preserved, base, storm, router, user_mask, flags, expect[4];
	char label[160];
	int c, um, fl, sm, rm;

	for (c = 0; c < 2; c++) {
		preserved = contexts[c];
		for (um = 0; um < (1 << 4); um++) {
			user_mask = bits_to_mask(user_bits, 4, um);
			for (fl = 0; fl < (1 << 4); fl++) {
				if (fl & ~um)
					continue;
				flags = bits_to_mask(user_bits, 4, fl);
				for (sm = 0; sm < (1 << 5); sm++) {
					storm = bits_to_mask(storm_bits, 5, sm);
					for (rm = 0; rm < (1 << 7); rm++) {
						struct yt921x_priv priv;

						router = bits_to_mask(router_bits, 7, rm);
						base = preserved | flags;
						priv.flood_unk_ucast_base_mask = preserved | BIT(1);
						priv.flood_mcast_base_mask = base;
						priv.flood_bcast_base_mask = preserved | BIT(0);
						priv.flood_storm_mask = storm;
						priv.ds.user_mask = user_mask;

						expect[0] = (preserved | BIT(1)) & YT921X_FILTER_PORTS_M;
						expect[1] = (base & ~router) & YT921X_FILTER_PORTS_M;
						expect[2] = (preserved | storm) & YT921X_FILTER_PORTS_M;
						expect[3] = ((preserved | BIT(0)) | storm) & YT921X_FILTER_PORTS_M;

						reset_ops();
						router_value = router;
						snprintf(label, sizeof(label),
							 "ctx%d um=0x%x fl=0x%x rm=0x%x sm=0x%x",
							 c, user_mask, flags, router, storm);
						check_ok(label, yt921x_apply_flood_filters_locked(&priv),
							 expect);
					}
				}
			}
		}
	}
}

static void test_known_flag_scope(void)
{
	u32 preserved, bit, router = BIT(10), storm = BIT(2), expect[4], unk_clear;
	char label[96];
	int c, b;

	for (c = 0; c < 2; c++) {
		preserved = contexts[c];
		for (b = 0; b < 4; b++) {
			struct yt921x_priv clear, set;

			bit = BIT(b);
			memset(&clear, 0, sizeof(clear));
			clear.flood_unk_ucast_base_mask = preserved;
			clear.flood_mcast_base_mask = preserved;
			clear.flood_bcast_base_mask = preserved | bit;
			clear.flood_storm_mask = storm;
			clear.ds.user_mask = BIT(0) | BIT(1) | BIT(2) | BIT(3);
			set = clear;
			set.flood_mcast_base_mask |= bit;

			unk_clear = (preserved & ~router) & YT921X_FILTER_PORTS_M;
			expect[0] = preserved;
			expect[2] = (preserved | storm) & YT921X_FILTER_PORTS_M;
			expect[3] = ((preserved | bit) | storm) & YT921X_FILTER_PORTS_M;
			expect[1] = unk_clear;
			reset_ops();
			router_value = router;
			snprintf(label, sizeof(label), "known-flag ctx%d bit%d clear", c, b);
			check_ok(label, yt921x_apply_flood_filters_locked(&clear), expect);

			expect[1] = unk_clear | bit;
			reset_ops();
			router_value = router;
			snprintf(label, sizeof(label), "known-flag ctx%d bit%d set", c, b);
			check_ok(label, yt921x_apply_flood_filters_locked(&set), expect);
		}
	}
}

static void test_faults(void)
{
	int c, i, j;
	char label[80];

	for (c = 0; c < 2; c++) {
		struct yt921x_priv priv;
		u32 expect[4];

		memset(&priv, 0, sizeof(priv));
		priv.flood_unk_ucast_base_mask = contexts[c] | BIT(1);
		priv.flood_mcast_base_mask = contexts[c] | BIT(0);
		priv.flood_bcast_base_mask = contexts[c] | BIT(0);
		priv.flood_storm_mask = BIT(2);
		priv.ds.user_mask = BIT(0) | BIT(1);
		expect[0] = priv.flood_unk_ucast_base_mask & YT921X_FILTER_PORTS_M;
		expect[1] = (priv.flood_mcast_base_mask & ~BIT(3)) & YT921X_FILTER_PORTS_M;
		expect[2] = (contexts[c] | BIT(2)) & YT921X_FILTER_PORTS_M;
		expect[3] = (priv.flood_bcast_base_mask | BIT(2)) & YT921X_FILTER_PORTS_M;

		reset_ops();
		router_value = BIT(3);
		fail_read = 1;
		snprintf(label, sizeof(label), "fault ctx%d read", c);
		if (yt921x_apply_flood_filters_locked(&priv) != -EIO)
			failf("%s: EIO not propagated", label);
		if (read_count != 1 || write_count != 0)
			failf("%s: read_count=%d write_count=%d", label,
			      read_count, write_count);

		for (i = 0; i < 4; i++) {
			reset_ops();
			router_value = BIT(3);
			fail_write = i;
			snprintf(label, sizeof(label), "fault ctx%d write%d", c, i);
			if (yt921x_apply_flood_filters_locked(&priv) != -EIO)
				failf("%s: EIO not propagated", label);
			if (read_count != 1 || write_count != i + 1)
				failf("%s: read_count=%d write_count=%d", label,
				      read_count, write_count);
			for (j = 0; j < i; j++)
				if (write_val[j] != expect[j])
					failf("%s: prior write %d val=0x%x want 0x%x",
					      label, j, write_val[j], expect[j]);
		}
	}
}

int main(void)
{
	test_matrix();
	test_known_flag_scope();
	test_faults();
	if (failures) {
		printf("%d check(s) failed\n", failures);
		return 1;
	}
	printf("PASS: yt921x multicast flood filters\n");
	return 0;
}
"""


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        type=Path,
        default=root / "target/linux/generic/files/drivers/net/dsa/yt921x_core.c",
        help="yt921x_core.c to extract the real function from (old source is "
        "a negative control)",
    )
    parser.add_argument(
        "--sanitize",
        action="store_true",
        help="build with address/undefined sanitizers and leak detection",
    )
    parser.add_argument("--cc", default="cc", help="C compiler to use")
    args = parser.parse_args()

    try:
        program = PREAMBLE + extract_apply(args.source.read_text()) + SCAFFOLDING
    except (HarnessError, OSError) as err:
        print(f"harness: {err}", file=sys.stderr)
        return 2

    with tempfile.TemporaryDirectory(prefix="yt921x-mcast-") as tmp:
        source = Path(tmp) / "test.c"
        binary = Path(tmp) / "test"
        source.write_text(program)
        flags = [
            "-std=gnu11", "-Wall", "-Wextra", "-Werror",
            "-Wno-unused-parameter", "-Wno-unused-function", "-O0",
        ]
        env = os.environ.copy()
        if args.sanitize:
            flags += [
                "-fsanitize=address,undefined",
                "-fno-sanitize-recover=all",
                "-fno-omit-frame-pointer",
            ]
            env["ASAN_OPTIONS"] = "detect_leaks=1"
        build = subprocess.run(
            [args.cc, *flags, "-o", str(binary), str(source)],
            capture_output=True,
            text=True,
        )
        if build.returncode:
            print(build.stdout, end="", file=sys.stderr)
            print(build.stderr, end="", file=sys.stderr)
            return 2
        run = subprocess.run(
            [str(binary)], capture_output=True, text=True, env=env
        )
        print(run.stdout, end="")
        print(run.stderr, end="", file=sys.stderr)
        return run.returncode


if __name__ == "__main__":
    sys.exit(main())

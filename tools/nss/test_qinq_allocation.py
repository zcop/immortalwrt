def _drop_dev_put(create_src: str) -> str:
    if "dev_put(ndev);" not in create_src:
        raise HarnessError("negative control: dev_put(ndev) not found in create")
    return create_src.replace("dev_put(ndev);", "", 1)


def compose(controller: Path, negative_control: bool) -> str:
    src = controller.read_text()
    match = MAX_NODES_RE.search(src)
    if not match:
        raise HarnessError("DSA_NSS_MAX_NODES not found in controller source")

    create = extract_function(src, "dsa_nss_node_create")
    if negative_control:
        create = _drop_dev_put(create)

    functions = [
        extract_function(src, "dsa_nss_is_root"),
        extract_function(src, "dsa_nss_node_destroy"),
        extract_function(src, "dsa_nss_node_owned_by"),
        extract_function(src, "dsa_nss_destroy_nodes"),
        create,
        extract_function(src, "dsa_nss_parent_ready"),
        extract_function(src, "dsa_nss_find_root"),
        extract_function(src, "dsa_nss_node_matches"),
        extract_function(src, "dsa_nss_root_wanted"),
        extract_function(src, "dsa_nss_resync"),
    ]

    return (
        PREAMBLE.replace("@MAX_NODES@", match.group(1))
        + extract_struct(src, "dsa_nss_node")
        + ";\n"
        + extract_struct(src, "dsa_nss_want")
        + ";\n"
        + TABLE
        + "\n"
        + "\n\n".join(functions)
        + "\n"
        + SCAFFOLDING
    )



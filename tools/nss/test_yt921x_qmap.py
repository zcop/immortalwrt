#!/usr/bin/env python3
"""Fake-register harness for yt921x priority-to-queue maps.

The queue-map macros and the bodies of yt921x_mqprio_apply() and
yt921x_qos_read_ucast_prio_qid_map() are extracted from the real sources.
Expected offsets are vendor literals: UC PRI0 is bits 2:0 and PRI5 is bits
22:20; MC PRI0 is bits 1:0 and PRI7 is bits 15:14.  Expectations are
literals, so an old header still compiles but fails.

Usage:
    tools/nss/test_yt921x_qmap.py
    tools/nss/test_yt921x_qmap.py --sanitize
    tools/nss/test_yt921x_qmap.py --header old/yt921x_enhanced.h
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "target/linux/generic/files/drivers/net/dsa/yt921x_enhanced.h"
SOURCE = ROOT / "target/linux/generic/files/drivers/net/dsa/yt921x_qos_tc.c"

DEFINES = (
    "YT921X_QOS_QUEUE_MAP_UCAST",
    "YT921X_QOS_QUEUE_MAP_MCAST",
    "YT921X_QOS_QUEUE_MAP_UCASTn",
    "YT921X_QOS_QUEUE_MAP_MCASTn",
    "YT921X_QOS_UCAST_QMAP_PRIO_SHIFT",
    "YT921X_QOS_UCAST_QMAP_PRIO_M",
    "YT921X_QOS_UCAST_QMAP_PRIO",
    "YT921X_QOS_MCAST_QMAP_PRIO_SHIFT",
    "YT921X_QOS_MCAST_QMAP_PRIO_M",
    "YT921X_QOS_MCAST_QMAP_PRIO",
    "YT921X_PRIO_NUM",
)


class HarnessError(RuntimeError):
    pass


def extract_define(src: str, name: str) -> str:
    pattern = (rf"(?m)^[ \t]*#define[ \t]+{re.escape(name)}"
               rf"(?![A-Za-z0-9_])(?:[^\n]*\\\n)*[^\n]*")
    match = re.search(pattern, src)
    if not match:
        raise HarnessError(f"macro {name} not found in header")
    return match.group(0)


def _skip_literal(src: str, pos: int) -> int:
    quote = src[pos]
    pos += 1
    while pos < len(src):
        if src[pos] == "\\":
            pos += 2
            continue
        if src[pos] == quote:
            return pos + 1
        pos += 1
    raise HarnessError("unterminated literal")


def _match_delim(src: str, pos: int, opening: str, closing: str) -> int:
    depth = 0
    while pos < len(src):
        if src.startswith("/*", pos):
            end = src.find("*/", pos + 2)
            if end < 0:
                raise HarnessError("unterminated comment")
            pos = end + 2
            continue
        if src.startswith("//", pos):
            end = src.find("\n", pos)
            pos = len(src) if end < 0 else end
            continue
        if src[pos] in ('"', "'"):
            pos = _skip_literal(src, pos)
            continue
        if src[pos] == opening:
            depth += 1
        elif src[pos] == closing:
            depth -= 1
            if depth == 0:
                return pos
        pos += 1
    raise HarnessError(f"unbalanced {opening}{closing}")


def _skip_space(src: str, pos: int) -> int:
    while pos < len(src):
        if src[pos].isspace():
            pos += 1
        elif src.startswith("/*", pos):
            end = src.find("*/", pos + 2)
            if end < 0:
                raise HarnessError("unterminated comment")
            pos = end + 2
        elif src.startswith("//", pos):
            end = src.find("\n", pos)
            pos = len(src) if end < 0 else end
        else:
            break
    return pos


def extract_function(src: str, name: str) -> str:
    """Return a definition, skipping earlier call sites with the same name."""
    pattern = re.compile(
        rf"(?m)^[ \t]*(?:static\s+)?[A-Za-z_][\w \t\*\n]*?\b{re.escape(name)}\s*\("
    )
    for match in pattern.finditer(src):
        paren = src.find("(", match.start(), match.end())
        brace = _skip_space(src, _match_delim(src, paren, "(", ")") + 1)
        if brace < len(src) and src[brace] == "{":
            end = _match_delim(src, brace, "{", "}")
            return src[match.start():end + 1]
    raise HarnessError(f"definition of {name} not found in C source")


PREAMBLE = r"""/* generated by test_yt921x_qmap.py; do not edit */
#include <errno.h>
#include <stdio.h>
#include <string.h>

typedef unsigned char u8;
typedef unsigned int u32;

#define GENMASK(h, l) (((~0U) << (l)) & (~0U >> (31 - (h))))
#define min_t(type, x, y) ((type)(x) < (type)(y) ? (type)(x) : (type)(y))

struct yt921x_priv {
	int unused;
};

"""

FAKE = r"""
#define FAKE_WORDS 64
static u32 fake_regs[FAKE_WORDS];
static int fake_fail_reg = -1;
static int fake_fail_write;
static int fake_writes;

static int fake_index(u32 reg)
{
	return (int)((reg - YT921X_QOS_QUEUE_MAP_UCAST) / 4);
}

static int yt921x_reg_read(struct yt921x_priv *priv, u32 reg, u32 *valp)
{
	(void)priv;
	if ((int)reg == fake_fail_reg && !fake_fail_write)
		return -EIO;
	*valp = fake_regs[fake_index(reg)];
	return 0;
}

static int yt921x_reg_write(struct yt921x_priv *priv, u32 reg, u32 val)
{
	(void)priv;
	fake_writes++;
	if ((int)reg == fake_fail_reg && fake_fail_write)
		return -EIO;
	fake_regs[fake_index(reg)] = val;
	return 0;
}

"""

CHECKS = r"""
static int failures;

static void check(const char *what, u32 got, u32 want)
{
	if (got != want) {
		fprintf(stderr, "FAIL: %s: got 0x%08x want 0x%08x\n",
			what, got, want);
		failures++;
	}
}

static void check_map(const char *what, const u8 *got, const u8 *want)
{
	int i;

	for (i = 0; i < YT921X_PRIO_NUM; i++)
		if (got[i] != want[i]) {
			fprintf(stderr, "FAIL: %s[%d]: got %u want %u\n",
				what, i, got[i], want[i]);
			failures++;
		}
}

static void test_layout(void)
{
	u32 uc_mask = 0;
	u32 mc_mask = 0;
	int i;

	check("uc shift p0", YT921X_QOS_UCAST_QMAP_PRIO_SHIFT(0), 0);
	check("uc shift p5", YT921X_QOS_UCAST_QMAP_PRIO_SHIFT(5), 20);
	check("uc mask p0", YT921X_QOS_UCAST_QMAP_PRIO_M(0), 0x00000007u);
	check("uc mask p5", YT921X_QOS_UCAST_QMAP_PRIO_M(5), 0x00700000u);
	check("mc shift p0", YT921X_QOS_MCAST_QMAP_PRIO_SHIFT(0), 0);
	check("mc shift p7", YT921X_QOS_MCAST_QMAP_PRIO_SHIFT(7), 14);
	check("mc mask p0", YT921X_QOS_MCAST_QMAP_PRIO_M(0), 0x00000003u);
	check("mc mask p7", YT921X_QOS_MCAST_QMAP_PRIO_M(7), 0x0000c000u);
	for (i = 0; i < YT921X_PRIO_NUM; i++) {
		uc_mask |= YT921X_QOS_UCAST_QMAP_PRIO_M(i);
		mc_mask |= YT921X_QOS_MCAST_QMAP_PRIO_M(i);
	}
	check("uc field coverage", uc_mask, 0x77777777u);
	check("mc field coverage", mc_mask, 0x0000ffffu);
}

static void test_map(int port, const u8 *map, u32 want_uc, u32 want_mc)
{
	struct yt921x_priv priv = { 0 };
	u32 uc_reg = YT921X_QOS_QUEUE_MAP_UCASTn(port);
	u32 mc_reg = YT921X_QOS_QUEUE_MAP_MCASTn(port);
	u8 got[YT921X_PRIO_NUM];
	int res;

	fake_regs[fake_index(uc_reg)] = 0x88888888u;
	fake_regs[fake_index(mc_reg)] = 0xdead0000u;
	res = yt921x_mqprio_apply(&priv, port, map);
	if (res) {
		fprintf(stderr, "FAIL: apply port %d: %d\n", port, res);
		failures++;
	}
	check("ucast map", fake_regs[fake_index(uc_reg)], 0x88888888u | want_uc);
	check("mcast map", fake_regs[fake_index(mc_reg)], 0xdead0000u | want_mc);

	memset(got, 0xaa, sizeof(got));
	res = yt921x_qos_read_ucast_prio_qid_map(&priv, port, got);
	if (res) {
		fprintf(stderr, "FAIL: readback port %d: %d\n", port, res);
		failures++;
	}
	check_map("ucast readback", got, map);
}

static void test_apply(void)
{
	static const u8 identity[YT921X_PRIO_NUM] = { 0, 1, 2, 3, 4, 5, 6, 7 };
	static const u8 asym[YT921X_PRIO_NUM] = { 5, 0, 7, 3, 1, 6, 4, 2 };

	test_map(0, identity, 0x76543210u, 0x0000ffe4u);
	test_map(2, identity, 0x76543210u, 0x0000ffe4u);
	test_map(8, identity, 0x76543210u, 0x0000ffe4u);
	test_map(0, asym, 0x24613705u, 0x0000bdf3u);
	test_map(2, asym, 0x24613705u, 0x0000bdf3u);
	test_map(8, asym, 0x24613705u, 0x0000bdf3u);
}

static void test_io_errors(void)
{
	static const u8 identity[YT921X_PRIO_NUM] = { 0, 1, 2, 3, 4, 5, 6, 7 };
	struct yt921x_priv priv = { 0 };
	const int port = 2;
	u32 uc_reg = YT921X_QOS_QUEUE_MAP_UCASTn(port);
	u32 mc_reg = YT921X_QOS_QUEUE_MAP_MCASTn(port);
	u8 map[YT921X_PRIO_NUM];
	int res;

	fake_regs[fake_index(uc_reg)] = 0x88888888u;
	fake_regs[fake_index(mc_reg)] = 0xdead0000u;

	fake_fail_reg = (int)uc_reg;
	fake_fail_write = 0;
	fake_writes = 0;
	res = yt921x_mqprio_apply(&priv, port, identity);
	check("ucast read error", (u32)res, (u32)-EIO);
	check("ucast read error writes", (u32)fake_writes, 0);

	fake_fail_reg = (int)mc_reg;
	fake_writes = 0;
	res = yt921x_mqprio_apply(&priv, port, identity);
	check("mcast read error", (u32)res, (u32)-EIO);
	check("mcast read error writes", (u32)fake_writes, 0);

	fake_fail_reg = (int)uc_reg;
	fake_fail_write = 1;
	res = yt921x_mqprio_apply(&priv, port, identity);
	check("ucast write error", (u32)res, (u32)-EIO);

	fake_fail_reg = (int)mc_reg;
	res = yt921x_mqprio_apply(&priv, port, identity);
	check("mcast write error", (u32)res, (u32)-EIO);

	fake_fail_reg = (int)uc_reg;
	fake_fail_write = 0;
	memset(map, 0xaa, sizeof(map));
	res = yt921x_qos_read_ucast_prio_qid_map(&priv, port, map);
	check("readback error", (u32)res, (u32)-EIO);
	check("readback error map", map[0], 0xaa);

	fake_fail_reg = -1;
}

int main(void)
{
	test_layout();
	test_apply();
	test_io_errors();
	if (failures) {
		fprintf(stderr, "%d check(s) failed\n", failures);
		return 1;
	}
	printf("PASS: yt921x priority-to-queue maps\n");
	return 0;
}
"""


def compose(header: Path) -> str:
    header_src = header.read_text()
    source_src = SOURCE.read_text()
    macros = "\n".join(extract_define(header_src, name) for name in DEFINES)
    functions = "\n\n".join(
        extract_function(source_src, name)
        for name in ("yt921x_mqprio_apply",
                     "yt921x_qos_read_ucast_prio_qid_map")
    )
    return PREAMBLE + macros + "\n" + FAKE + functions + "\n" + CHECKS


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--header", type=Path, default=HEADER,
                        help="header to extract the queue-map macros from")
    parser.add_argument("--sanitize", action="store_true",
                        help="build and run with ASan/UBSan/LSan")
    parser.add_argument("--cc", default=os.environ.get("CC", "cc"))
    args = parser.parse_args()

    try:
        program = compose(args.header)
    except (HarnessError, OSError) as err:
        print(f"harness: {err}", file=sys.stderr)
        return 2

    cflags = ["-std=gnu11", "-Wall", "-Wextra", "-Werror",
              "-Wno-unused-parameter", "-O0"]
    env = dict(os.environ)
    if args.sanitize:
        cflags += ["-fsanitize=address,undefined",
                   "-fno-omit-frame-pointer", "-g"]
        env["ASAN_OPTIONS"] = "detect_leaks=1:abort_on_error=1"
        env["UBSAN_OPTIONS"] = "halt_on_error=1:print_stacktrace=1"

    with tempfile.TemporaryDirectory(prefix="yt921x-qmap-") as tmp:
        source = Path(tmp) / "test.c"
        binary = Path(tmp) / "test"
        source.write_text(program)
        build = subprocess.run(
            [args.cc, *cflags, "-o", str(binary), str(source)],
            capture_output=True, text=True,
        )
        if build.returncode:
            print(build.stdout, end="", file=sys.stderr)
            print(build.stderr, end="", file=sys.stderr)
            return 2
        run = subprocess.run([str(binary)], capture_output=True,
                             text=True, env=env)
        print(run.stdout, end="")
        print(run.stderr, end="", file=sys.stderr)
        return run.returncode


if __name__ == "__main__":
    sys.exit(main())
